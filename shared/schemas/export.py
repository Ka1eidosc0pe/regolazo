"""Export contracts: JSON Schema files, JSON fixtures, TS enum constants and typed TS fixtures.

Usage:
    uv run python -m shared.schemas.export           # write everything
    uv run python -m shared.schemas.export --check   # exit 1 if any generated file is stale (CI)

TS interfaces are then generated from the bundle by ``npm run gen:types`` in web/ (json-schema-to-typescript).
"""

import argparse
import json
import re
import sys
from pathlib import Path
from types import ModuleType
from typing import Any, Literal, get_args, get_origin

from pydantic.json_schema import models_json_schema

from shared.schemas import (
    ROOT_MODELS,
    SCHEMA_VERSION,
    actions,
    common,
    enums,
    labels,
    meta,
    moments,
    narrative,
    overlay,
    rollout,
    state,
    stats,
    stream,
)
from shared.schemas.fixtures import EXAMPLES, FIXTURES

ROOT = Path(__file__).resolve().parents[2]
JSON_DIR = ROOT / "shared" / "schemas" / "json"
FIXTURE_DIR = ROOT / "shared" / "fixtures"
TS_GEN_DIR = ROOT / "web" / "src" / "types" / "generated"
TS_FIXTURES = ROOT / "web" / "tests" / "generated" / "fixtures.ts"

ENUM_MODULES: tuple[ModuleType, ...] = (
    common,
    enums,
    meta,
    state,
    actions,
    moments,
    rollout,
    overlay,
    narrative,
    labels,
    stream,
    stats,
)
DRAFT = "http://json-schema.org/draft-07/schema#"
"""Exported schemas are draft-07: tuples use array-form ``items``, which every TS/JS tool understands."""
HEADER = "// GENERATED by `uv run python -m shared.schemas.export`. Do not edit by hand.\n"


def _normalize(node: Any, *, keep_title: bool = False) -> Any:
    """Make Pydantic's draft 2020-12 output friendly to json-schema-to-typescript.

    - tuples: ``prefixItems`` -> draft-07 ``items`` array, so TS gets typed tuples
    - drop property-level ``title`` so the generator doesn't emit an alias type per field
    """
    if isinstance(node, list):
        return [_normalize(v) for v in node]
    if not isinstance(node, dict):
        return node
    out: dict[str, Any] = {}
    for key, value in node.items():
        if key == "title" and not keep_title:
            continue
        if key == "prefixItems":
            out["items"] = _normalize(value)
            out["additionalItems"] = False
            continue
        if key == "$defs":
            out[key] = {name: _normalize(d, keep_title=True) for name, d in value.items()}
            continue
        out[key] = _normalize(value)
    return out


def _dump(obj: Any) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False) + "\n"


def model_schemas() -> dict[str, str]:
    files: dict[str, str] = {}
    for model in ROOT_MODELS:
        schema = model.model_json_schema(mode="serialization")
        schema = {
            "$schema": DRAFT,
            "$id": f"https://regolazo.dev/schemas/{SCHEMA_VERSION}/{model.__name__}.json",
            **schema,
        }
        files[f"{model.__name__}.schema.json"] = _dump(_normalize(schema, keep_title=True))
    _, defs = models_json_schema([(m, "serialization") for m in ROOT_MODELS], ref_template="#/$defs/{model}")
    bundle = {
        "$schema": DRAFT,
        "title": "Contracts",
        "description": f"All ReGolazo root contracts, schema version {SCHEMA_VERSION}.",
        "type": "object",
        "properties": {m.__name__: {"$ref": f"#/$defs/{m.__name__}"} for m in ROOT_MODELS},
        "required": [m.__name__ for m in ROOT_MODELS],
        "additionalProperties": False,
        "$defs": defs["$defs"],
    }
    files["contracts.schema.json"] = _dump(_normalize(bundle, keep_title=True))
    return files


def fixture_files() -> dict[str, str]:
    files = {f"{name}.json": _dump(model.model_dump(mode="json")) for name, model in FIXTURES.items()}
    for name, items in EXAMPLES.items():
        files[f"examples/{name}.json"] = _dump([m.model_dump(mode="json") for m in items])
    return files


def _upper_snake(name: str) -> str:
    return re.sub(r"(?<!^)(?=[A-Z])", "_", name).upper()


def literal_aliases() -> dict[str, tuple[str | int, ...]]:
    found: dict[str, tuple[str | int, ...]] = {}
    for module in ENUM_MODULES:
        for name, value in vars(module).items():
            if name[0].isupper() and get_origin(value) is Literal and name not in found:
                found[name] = get_args(value)
    return dict(sorted(found.items()))


def enums_ts() -> str:
    lines = [HEADER, f'export const SCHEMA_VERSION = "{SCHEMA_VERSION}";\n']
    for name, values in literal_aliases().items():
        const = _upper_snake(name)
        lines.append(f"export const {const} = {json.dumps(list(values))} as const;")
        lines.append(f"export type {name} = (typeof {const})[number];\n")
    return "\n".join(lines)


def fixtures_ts() -> str:
    names = sorted(FIXTURES)
    lines = [
        HEADER,
        "// Each fixture is assigned to its generated type, so `tsc` proves Python output conforms to the TS types.",
        f'import type {{ {", ".join(names)} }} from "../../src/types/generated/contracts";\n',
    ]
    for name in names:
        body = json.dumps(FIXTURES[name].model_dump(mode="json"), indent=2, ensure_ascii=False)
        lines.append(f"export const {name[0].lower() + name[1:]}Fixture: {name} = {body};\n")
    for name, items in sorted(EXAMPLES.items()):
        body = json.dumps([m.model_dump(mode="json") for m in items], indent=2, ensure_ascii=False)
        lines.append(f"export const {name[0].lower() + name[1:]}Examples: {name}[] = {body};\n")
    return "\n".join(lines)


def outputs() -> dict[Path, str]:
    """Every generated file and its expected content."""
    result = {JSON_DIR / name: text for name, text in model_schemas().items()}
    result.update({FIXTURE_DIR / name: text for name, text in fixture_files().items()})
    result[TS_GEN_DIR / "enums.ts"] = enums_ts()
    result[TS_FIXTURES] = fixtures_ts()
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()
    stale: list[str] = []
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                stale.append(str(path.relative_to(ROOT)))
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    if args.check:
        if stale:
            print("Stale generated files (run `uv run python -m shared.schemas.export`):\n  " + "\n  ".join(stale))
            return 1
        print("Generated contract files are up to date.")
    else:
        print(f"Wrote {len(outputs())} files (schema version {SCHEMA_VERSION}).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
